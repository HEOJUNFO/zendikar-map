// 지역 상세(자식 지도) — 작은 대상이 모였거나 자리가 붐비는 지역을 큰 축척으로 따로 그린 그림. 세계 지도를 깊이 확대하면 그 자리에 나온다.
// 그림은 scripts/childmaps/art/<id>.js → src/map/childmaps/<id>.ts (node scripts/childmaps/to_ts.mjs). 이 파일이 원본이다 — 손으로 고친다.
// 그림 좌표는 bounds 를 그림 크기(size)로 늘린 것이라 해안·호수·숲, 장소·카드 표시의 자리가 세계 지도와 맞는다.
// 페이즈와 상관없이 나오고, 그 안의 작은 대상(페이즈 카드의 childMap)만 그 카드의 페이즈를 켰을 때 그린다. 공식 자료가 그 무렵 모습이 달랐다고 밝힌
// 지형지물은 그림의 페이즈 문으로 그 페이즈에서만 바꿔 그리고(CLAUDE.md '그 무렵 모습'), 그 해석은 note 에 적는다.
// 붐비는 지역 상세 안의 한 구역은 더 큰 축척의 '더 깊은 지역 상세'(parent)로 나눌 수 있다 — 부모 뒤에 두고, 범위는 부모 범위 안,
// 그림은 부모보다 깊은 tier 가 되게(그림 단위 ÷ 지도 단위 ≈ 10). 부모 그림은 나와 있는 더 깊은 지역 상세 자리에서 물러난다 (CLAUDE.md 붐빔 규칙 2).
// 장소는 지역 상세마다 하나다.

export interface ChildMap {
  id: string
  /** 그 지역의 장소(locations.ts id) — 이름은 이 장소의 이름. 이름 뒤에 접힌 지도 아이콘이 붙고, 장소 패널의 '가까이 보기'가 이 범위로 간다 */
  place: string
  /** 더 깊은 지역 상세면 그것을 담은 부모 지역 상세의 id (한 겹만 — 부모는 부모가 없다) */
  parent?: string
  /** 지역 상세가 그리는 범위 (세계 지도 단위) — 이 범위의 해안·장소 자리를 가져와 늘려 그린다. 더 깊은 지역 상세는 부모 범위 안 (변은 겹쳐도 된다) */
  bounds: { x0: number; y0: number; x1: number; y1: number }
  /** 해석 안내 — 공식 서술 가운데 이 그림이 따른 것과 이 지도의 판단으로 그린 것 (장소 패널에 보인다) */
  note?: string
}

