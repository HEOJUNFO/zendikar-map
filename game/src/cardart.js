export function ringPts(cx, cy, rx, ry) {
  const pts = [];
  for (let i = 0; i <= 16; i++) { const a = i / 16 * Math.PI * 2; pts.push(cx + Math.cos(a) * rx, cy + Math.sin(a) * ry); }
  return pts;
}

